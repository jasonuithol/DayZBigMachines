#!/usr/bin/env python3
"""Writes BigMachines/scripts/4_World/BigMachines/BM_WreckSites.c from
data/construction_vehicles.csv and data/farm_vehicles.csv: every map's bulldozer, digger and
combine harvester wrecks and tower cranes, the ones BM_Wrecks can swap for working machines.

    python3 tools/make_sites.py
"""
import csv
import os
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSVS = [os.path.join(ROOT, "data", n) for n in ("construction_vehicles.csv", "farm_vehicles.csv")]
OUT = os.path.join(ROOT, "BigMachines", "scripts", "4_World", "BigMachines", "BM_WreckSites.c")

# CSV (class, model) -> (kind constant, what to match: a class name or a model file, lower case)
KINDS = {
    ("", "wreck_bulldozer.p3d"): ("BM_WreckSite.DOZER", "wreck_bulldozer.p3d"),
    ("", "wreck_digger.p3d"): ("BM_WreckSite.DIGGER", "wreck_digger.p3d"),
    ("Land_Construction_Crane", ""): ("BM_WreckSite.CRANE", "land_construction_crane"),
    ("Land_Wreck_Harverster", ""): ("BM_WreckSite.COMBINE", "land_wreck_harverster"),   # sic
}


def main():
    sites = defaultdict(list)
    for path in CSVS:
        with open(path) as f:
            for row in csv.DictReader(f):
                key = (row["class"], row["model"])
                if key not in KINDS:
                    continue
                kind, match = KINDS[key]
                sites[row["map"]].append((kind, match, row["x"], row["y"], row["z"]))
    lines = [
        "// Generated by tools/make_sites.py from data/construction_vehicles.csv and data/farm_vehicles.csv - don't edit.",
        "//! Where each map's machine wrecks are (headless scans of the maps,",
        "//! DayZ 1.30): the ones BM_Wrecks may swap for working machines",
        "class BM_WreckSites",
        "{",
        "\t//! Every site on this world (GetGame().GetWorldName(), any case); none on other maps",
        "\tstatic void Get(string world, array<ref BM_WreckSite> sites)",
        "\t{",
        "\t\tworld.ToLower();",
    ]
    for world in sorted(sites):
        lines.append(f'\t\tif (world == "{world}")')
        lines.append("\t\t{")
        for kind, match, x, y, z in sites[world]:
            lines.append(f'\t\t\tsites.Insert(new BM_WreckSite({kind}, "{match}", "{x} {y} {z}"));')
        lines.append("\t\t}")
    lines += ["\t}", "}", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    for world in sorted(sites):
        counts = defaultdict(int)
        for s in sites[world]:
            counts[s[0].split(".")[1]] += 1
        print(world, dict(counts))


main()
